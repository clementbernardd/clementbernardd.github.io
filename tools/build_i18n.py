"""Generate assets/i18n-fr.js from tools/i18n_fr_source.py (run after editing the French translations)."""
import json, pathlib, runpy
root = pathlib.Path(__file__).resolve().parent.parent
fr = runpy.run_path(str(root / "tools" / "i18n_fr_source.py"))["FR"]
js = "// Generated by tools/build_i18n.py from tools/i18n_fr_source.py: edit the source, not this file.\nwindow.I18N_FR = " + json.dumps(fr, ensure_ascii=False, indent=0) + ";\n"
(root / "assets" / "i18n-fr.js").write_text(js, encoding="utf-8")
print(len(fr), "French entries")
